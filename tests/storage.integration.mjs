import assert from 'node:assert/strict';
const base = 'http://localhost:8795';
const session = await fetch(base + '/api/session');
const cookie = session.headers.get('set-cookie').split(';')[0];
const body = new FormData();body.set('file', new File(['{"v":"5.7.0","w":64,"h":64,"ip":0,"op":60,"fr":30,"layers":[]}'], 'storage-check.json'));
const upload = await fetch(base+'/api/files',{method:'POST',headers:{Cookie:cookie,Origin:base},body});
assert.equal(upload.status,201,await upload.clone().text());
const file=await upload.json();
const saved=await fetch(file.url);assert.equal(saved.status,200);assert.equal((await saved.json()).w,64);
const list=await (await fetch(base+'/api/files',{headers:{Cookie:cookie}})).json();
assert.ok(list.files.some(item=>item.id===file.id));
const other=await fetch(base+'/api/session');
const otherCookie=other.headers.get('set-cookie').split(';')[0];
const otherList=await (await fetch(base+'/api/files',{headers:{Cookie:otherCookie}})).json();
assert.ok(!otherList.files.some(item=>item.id===file.id));
const hide=await fetch(base+`/api/files/${file.id}/hide`,{method:'POST',headers:{Cookie:cookie,Origin:base}});assert.equal(hide.status,200);
const hidden=await (await fetch(base+'/api/files',{headers:{Cookie:cookie}})).json();assert.ok(!hidden.files.some(item=>item.id===file.id));
assert.equal((await fetch(file.url)).status,200);
console.log('D1 + R2 upload/read/list/isolation/hide integration passed');
